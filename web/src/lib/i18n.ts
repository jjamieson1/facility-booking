const stored = typeof localStorage !== "undefined" ? localStorage.getItem("lang") : null;

void i18n.use(initReactI18next).init({
  resources: { en: { translation: en }, fr: { translation: fr } },
  lng: stored ?? "en",
  fallbackLng: "en",
  interpolation: { escapeValue: false },
});

// Keep the document language in sync so screen readers announce content in the
// right language (WCAG 3.1.1/3.1.2).
function syncHtmlLang(lng: string) {
  if (typeof document !== "undefined") document.documentElement.lang = lng.startsWith("fr") ? "fr" : "en";
}
syncHtmlLang(i18n.language);
i18n.on("languageChanged", syncHtmlLang);

export function setLanguage(lng: "en" | "fr") {
  void i18n.changeLanguage(lng);
  if (typeof localStorage !== "undefined") localStorage.setItem("lang", lng);
}

